-- medication reasons. One row per code.
CREATE TABLE analytics.dim_condition (
    condition_key  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    condition_code TEXT NOT NULL UNIQUE,
    description    TEXT
);
INSERT INTO analytics.dim_condition (condition_key, condition_code, description)
VALUES (-1, 'UNKNOWN', 'Not recorded');
INSERT INTO analytics.dim_condition (condition_code, description)
SELECT DISTINCT ON (code) code, description
FROM (
    SELECT code,        description        FROM core.conditions
    UNION ALL
    SELECT reason_code, reason_description FROM core.encounters  WHERE reason_code IS NOT NULL
    UNION ALL
    SELECT reason_code, reason_description FROM core.medications WHERE reason_code IS NOT NULL
) AS all_codes
ORDER BY code, description NULLS LAST;


-- =====================================================================
-- 3. dim_patient: Type 2 slowly changing dimension (tracks insurance)
-- =====================================================================
CREATE TABLE analytics.dim_patient (
    patient_key      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id       TEXT    NOT NULL,
    gender           CHAR(1),
    race             TEXT,
    ethnicity        TEXT,
    birth_date       DATE,
    death_date       DATE,
    city             TEXT,
    county           TEXT,
    payer_key        INTEGER NOT NULL REFERENCES analytics.dim_payer (payer_key),
    effective_from   DATE    NOT NULL,
    effective_to     DATE    NOT NULL,         -- exclusive; 9999-12-31 = open
    is_current       BOOLEAN NOT NULL,
    CHECK (effective_from < effective_to),
    UNIQUE (patient_id, effective_from)
);
INSERT INTO analytics.dim_patient
    (patient_key, patient_id, payer_key, effective_from, effective_to, is_current)
VALUES (-1, 'UNKNOWN', -1, DATE '1900-01-01', DATE '9999-12-31', TRUE);

WITH periods AS (
    -- one insurance period per patient per start date
    SELECT DISTINCT ON (patient_id, start_ts::date)
           patient_id,
           start_ts::date AS start_d,
           payer_id
    FROM (SELECT patient_id, start_date AS start_ts, payer_id
          FROM core.payer_transitions) t
    ORDER BY patient_id, start_ts::date, start_ts DESC
),
flagged AS (
    -- 1 whenever the payer differs from the previous period
    SELECT *,
           CASE WHEN payer_id IS NOT DISTINCT FROM
                     LAG(payer_id) OVER (PARTITION BY patient_id ORDER BY start_d)
                THEN 0 ELSE 1 END AS is_new_payer
    FROM periods
),
grouped AS (
    -- running total of changes = an "island" id per run of the same payer
    SELECT *,
           SUM(is_new_payer) OVER (PARTITION BY patient_id ORDER BY start_d) AS island
    FROM flagged
),
islands AS (
    SELECT patient_id, island, MIN(start_d) AS start_d, MIN(payer_id) AS payer_id
    FROM grouped
    GROUP BY patient_id, island
),
versions AS (
    SELECT patient_id, payer_id,
           ROW_NUMBER() OVER (PARTITION BY patient_id ORDER BY start_d) AS version_no,
           start_d,
           LEAD(start_d, 1, DATE '9999-12-31')
               OVER (PARTITION BY patient_id ORDER BY start_d) AS end_d
    FROM islands
)
INSERT INTO analytics.dim_patient
    (patient_id, gender, race, ethnicity, birth_date, death_date, city, county,
     payer_key, effective_from, effective_to, is_current)
SELECT p.patient_id, p.gender, p.race, p.ethnicity, p.birth_date, p.death_date,
       p.city, p.county,
       COALESCE(dp.payer_key, -1),
       -- the first version reaches back to birth so no early event is orphaned
       CASE WHEN v.version_no IS NULL OR v.version_no = 1
            THEN LEAST(p.birth_date, COALESCE(v.start_d, p.birth_date))
            ELSE v.start_d END,
       COALESCE(v.end_d, DATE '9999-12-31'),
       COALESCE(v.end_d, DATE '9999-12-31') = DATE '9999-12-31'
FROM core.patients p
LEFT JOIN versions v           ON v.patient_id = p.patient_id
LEFT JOIN analytics.dim_payer dp ON dp.payer_id = v.payer_id;


-- =====================================================================
-- 4. fact_encounters + incremental upsert procedure
-- =====================================================================
CREATE TABLE analytics.fact_encounters (
    encounter_key         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    encounter_id          TEXT     NOT NULL UNIQUE,   -- natural key, used by the upsert
    patient_key           INTEGER  NOT NULL REFERENCES analytics.dim_patient      (patient_key),
    provider_key          INTEGER  NOT NULL REFERENCES analytics.dim_provider     (provider_key),
    organization_key      INTEGER  NOT NULL REFERENCES analytics.dim_organization (organization_key),
    payer_key             INTEGER  NOT NULL REFERENCES analytics.dim_payer        (payer_key),
    reason_condition_key  INTEGER  NOT NULL REFERENCES analytics.dim_condition    (condition_key),
    start_date_key        INTEGER  NOT NULL REFERENCES analytics.dim_date         (date_key),
    end_date_key          INTEGER           REFERENCES analytics.dim_date         (date_key),
    start_ts              TIMESTAMP NOT NULL,
    stop_ts               TIMESTAMP,
    encounter_class       TEXT     NOT NULL,
    encounter_code        TEXT,
    encounter_description TEXT,
    age_at_encounter      SMALLINT,
    length_of_stay_hours  NUMERIC(10,2),
    base_encounter_cost   NUMERIC(12,2),
    total_claim_cost      NUMERIC(12,2),
    payer_coverage        NUMERIC(12,2),
    patient_paid          NUMERIC(12,2),             -- total cost minus payer coverage
    loaded_at             TIMESTAMP NOT NULL DEFAULT now(),
    updated_at            TIMESTAMP
);

CREATE PROCEDURE analytics.load_fact_encounters()
LANGUAGE plpgsql
AS $$
DECLARE
    v_inserted BIGINT;
    v_updated  BIGINT;
BEGIN
    WITH upserted AS (
        INSERT INTO analytics.fact_encounters AS f
            (encounter_id, patient_key, provider_key, organization_key, payer_key,
             reason_condition_key, start_date_key, end_date_key, start_ts, stop_ts,
             encounter_class, encounter_code, encounter_description,
             age_at_encounter, length_of_stay_hours, base_encounter_cost,
             total_claim_cost, payer_coverage, patient_paid)
        SELECT
            e.encounter_id,
            COALESCE(dpat.patient_key, -1),
            COALESCE(dprov.provider_key, -1),
            COALESCE(dorg.organization_key, -1),
            COALESCE(dpay.payer_key, -1),
            COALESCE(dcond.condition_key, -1),
            TO_CHAR(e.start_ts, 'YYYYMMDD')::integer,
            TO_CHAR(e.stop_ts,  'YYYYMMDD')::integer,
            e.start_ts,
            e.stop_ts,
            e.encounter_class,
            e.code,
            e.description,
            EXTRACT(YEAR FROM AGE(e.start_ts::date, p.birth_date)),
            ROUND(EXTRACT(EPOCH FROM (e.stop_ts - e.start_ts)) / 3600.0, 2),
            e.base_encounter_cost,
            e.total_claim_cost,
            e.payer_coverage,
            GREATEST(e.total_claim_cost - COALESCE(e.payer_coverage, 0), 0)
        FROM core.encounters e
        JOIN core.patients p ON p.patient_id = e.patient_id
        LEFT JOIN analytics.dim_patient dpat
               ON dpat.patient_id = e.patient_id
              AND e.start_ts::date >= dpat.effective_from
              AND e.start_ts::date <  dpat.effective_to
        LEFT JOIN analytics.dim_provider     dprov ON dprov.provider_id     = e.provider_id
        LEFT JOIN analytics.dim_organization dorg  ON dorg.organization_id  = e.organization_id
        LEFT JOIN analytics.dim_payer        dpay  ON dpay.payer_id         = e.payer_id
        LEFT JOIN analytics.dim_condition    dcond ON dcond.condition_code  = e.reason_code
        ON CONFLICT (encounter_id) DO UPDATE SET
            patient_key           = EXCLUDED.patient_key,
            provider_key          = EXCLUDED.provider_key,
            organization_key      = EXCLUDED.organization_key,
            payer_key             = EXCLUDED.payer_key,
            reason_condition_key  = EXCLUDED.reason_condition_key,
            start_date_key        = EXCLUDED.start_date_key,
            end_date_key          = EXCLUDED.end_date_key,
            start_ts              = EXCLUDED.start_ts,
            stop_ts               = EXCLUDED.stop_ts,
            encounter_class       = EXCLUDED.encounter_class,
            encounter_code        = EXCLUDED.encounter_code,
            encounter_description = EXCLUDED.encounter_description,
            age_at_encounter      = EXCLUDED.age_at_encounter,
            length_of_stay_hours  = EXCLUDED.length_of_stay_hours,
            base_encounter_cost   = EXCLUDED.base_encounter_cost,
            total_claim_cost      = EXCLUDED.total_claim_cost,
            payer_coverage        = EXCLUDED.payer_coverage,
            patient_paid          = EXCLUDED.patient_paid,
            updated_at            = now()
        -- only touch rows whose values actually changed
        WHERE (f.patient_key, f.provider_key, f.organization_key, f.payer_key,
               f.reason_condition_key, f.start_ts, f.stop_ts, f.encounter_class,
               f.encounter_code, f.total_claim_cost, f.payer_coverage)
              IS DISTINCT FROM
              (EXCLUDED.patient_key, EXCLUDED.provider_key, EXCLUDED.organization_key,
               EXCLUDED.payer_key, EXCLUDED.reason_condition_key, EXCLUDED.start_ts,
               EXCLUDED.stop_ts, EXCLUDED.encounter_class, EXCLUDED.encounter_code,
               EXCLUDED.total_claim_cost, EXCLUDED.payer_coverage)
        RETURNING (xmax = 0) AS was_inserted     -- xmax = 0 means a fresh insert
    )
    SELECT COUNT(*) FILTER (WHERE was_inserted),
           COUNT(*) FILTER (WHERE NOT was_inserted)
    INTO v_inserted, v_updated
    FROM upserted;

    RAISE NOTICE 'fact_encounters load: % inserted, % updated', v_inserted, v_updated;
END;
$$;

CALL analytics.load_fact_encounters();


