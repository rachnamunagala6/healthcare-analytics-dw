CREATE TABLE analytics.fact_diagnoses (
    diagnosis_key     BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    patient_key       INTEGER NOT NULL REFERENCES analytics.dim_patient   (patient_key),
    condition_key     INTEGER NOT NULL REFERENCES analytics.dim_condition (condition_key),
    onset_date_key    INTEGER NOT NULL REFERENCES analytics.dim_date      (date_key),
    resolved_date_key INTEGER          REFERENCES analytics.dim_date      (date_key),
    encounter_id      TEXT,
    age_at_onset      SMALLINT,
    is_active         BOOLEAN NOT NULL,          -- no resolution date recorded
    duration_days     INTEGER
);

INSERT INTO analytics.fact_diagnoses
    (patient_key, condition_key, onset_date_key, resolved_date_key,
     encounter_id, age_at_onset, is_active, duration_days)
SELECT
    COALESCE(dpat.patient_key, -1),
    COALESCE(dcond.condition_key, -1),
    TO_CHAR(c.start_date, 'YYYYMMDD')::integer,
    TO_CHAR(c.stop_date,  'YYYYMMDD')::integer,
    c.encounter_id,
    EXTRACT(YEAR FROM AGE(c.start_date, p.birth_date)),
    c.stop_date IS NULL,
    c.stop_date - c.start_date
FROM core.conditions c
JOIN core.patients p ON p.patient_id = c.patient_id
LEFT JOIN analytics.dim_patient dpat
       ON dpat.patient_id = c.patient_id
      AND c.start_date >= dpat.effective_from
      AND c.start_date <  dpat.effective_to
LEFT JOIN analytics.dim_condition dcond ON dcond.condition_code = c.code;


