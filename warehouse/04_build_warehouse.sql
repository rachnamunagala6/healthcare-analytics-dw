-- =====================================================================
-- 1. dim_date: one row per calendar day covering all clinical activity
-- =====================================================================
CREATE TABLE analytics.dim_date (
    date_key     INTEGER PRIMARY KEY,          -- YYYYMMDD, e.g. 20240131
    full_date    DATE     NOT NULL UNIQUE,
    year         SMALLINT NOT NULL,
    quarter      SMALLINT NOT NULL,
    month        SMALLINT NOT NULL,
    month_name   TEXT     NOT NULL,
    year_month   TEXT     NOT NULL,            -- e.g. 2024-01
    day_of_week  SMALLINT NOT NULL,            -- 1 = Monday ... 7 = Sunday
    day_name     TEXT     NOT NULL,
    is_weekend   BOOLEAN  NOT NULL
);

INSERT INTO analytics.dim_date
SELECT
    TO_CHAR(d, 'YYYYMMDD')::integer,
    d,
    EXTRACT(YEAR    FROM d),
    EXTRACT(QUARTER FROM d),
    EXTRACT(MONTH   FROM d),
    TRIM(TO_CHAR(d, 'Month')),
    TO_CHAR(d, 'YYYY-MM'),
    EXTRACT(ISODOW  FROM d),
    TRIM(TO_CHAR(d, 'Day')),
    EXTRACT(ISODOW  FROM d) IN (6, 7)
FROM generate_series(
        (SELECT LEAST(MIN(start_ts)::date,
                      (SELECT MIN(start_date) FROM core.conditions),
                      (SELECT MIN(start_ts)::date FROM core.medications))
         FROM core.encounters),
        (SELECT GREATEST(MAX(COALESCE(stop_ts, start_ts))::date,
                         (SELECT MAX(COALESCE(stop_date, start_date)) FROM core.conditions),
                         (SELECT MAX(COALESCE(stop_ts, start_ts))::date FROM core.medications))
         FROM core.encounters),
        INTERVAL '1 day') AS g(d);


