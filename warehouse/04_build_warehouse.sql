LEFT JOIN analytics.dim_condition dcond ON dcond.condition_code  = m.reason_code;


-- =====================================================================
-- 7. Reconciliation: does the warehouse match the core layer?
-- =====================================================================
SELECT check_name, core_value, warehouse_value,
       CASE WHEN core_value = warehouse_value THEN 'OK' ELSE 'MISMATCH' END AS status
FROM (
              SELECT 'encounter rows' AS check_name,
                     (SELECT COUNT(*) FROM core.encounters)::numeric           AS core_value,
                     (SELECT COUNT(*) FROM analytics.fact_encounters)::numeric AS warehouse_value
    UNION ALL SELECT 'encounter total claim cost',
                     (SELECT COALESCE(SUM(total_claim_cost), 0) FROM core.encounters),
                     (SELECT COALESCE(SUM(total_claim_cost), 0) FROM analytics.fact_encounters)
    UNION ALL SELECT 'diagnosis rows',
                     (SELECT COUNT(*) FROM core.conditions),
                     (SELECT COUNT(*) FROM analytics.fact_diagnoses)
    UNION ALL SELECT 'medication rows',
                     (SELECT COUNT(*) FROM core.medications),
                     (SELECT COUNT(*) FROM analytics.fact_medications)
    UNION ALL SELECT 'medication total cost',
                     (SELECT COALESCE(SUM(total_cost), 0) FROM core.medications),
                     (SELECT COALESCE(SUM(total_cost), 0) FROM analytics.fact_medications)
    UNION ALL SELECT 'patients (current versions)',
                     (SELECT COUNT(*) FROM core.patients),
                     (SELECT COUNT(*) FROM analytics.dim_patient
                      WHERE is_current AND patient_key <> -1)
    UNION ALL SELECT 'encounters linked to Unknown patient (should be 0)',
                     0,
                     (SELECT COUNT(*) FROM analytics.fact_encounters WHERE patient_key = -1)
) AS checks;

-- Bonus: how many patients changed insurance (i.e. have more than one version)?
SELECT COUNT(*) FILTER (WHERE versions > 1) AS patients_with_insurance_changes,
       COUNT(*)                             AS total_patients,
       MAX(versions)                        AS max_versions_for_one_patient
FROM (SELECT patient_id, COUNT(*) AS versions
      FROM analytics.dim_patient
      WHERE patient_key <> -1
      GROUP BY patient_id) v;
