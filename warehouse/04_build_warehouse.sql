/* =====================================================================
   04_build_warehouse.sql
   Phase 3: Star schema data warehouse in the analytics schema.

   Model
   - Dimensions : dim_date, dim_patient (Type 2 SCD), dim_provider,
                  dim_organization, dim_payer, dim_condition
   - Facts      : fact_encounters  (grain: one row per encounter)
                  fact_diagnoses   (grain: one row per diagnosis)
                  fact_medications (grain: one row per prescription)

   Techniques shown
   - Surrogate keys, plus an "Unknown" member (key -1) in every dimension,
     so facts never have NULL foreign keys or silently drop rows
   - dim_patient is a Type 2 slowly changing dimension: a new version of a
     patient is created each time their insurance changes, with
     effective_from / effective_to / is_current. Consecutive periods on the
     same payer are collapsed with a gaps-and-islands query.
   - Facts join to the patient version that was in effect on the event date
   - fact_encounters is loaded by a stored procedure that does an
     incremental upsert (INSERT ... ON CONFLICT DO UPDATE): new encounters
     are inserted, changed ones are updated, unchanged ones are skipped.
   - Reconciliation checks compare warehouse totals with the core layer

   Re-runnable. Run while connected to healthcare_dw, after 02_build_core.sql.
   ===================================================================== */

